"""Generate ``odin/rst/unicode_tables.odin`` from CPython's ``unicodedata`` and docutils.

The reST parser must classify characters exactly like docutils does in
Python: ``\\s`` / ``str.isspace()``, ``\\w`` / ``str.isalnum()``, combining
characters, East Asian width and the inline-markup punctuation classes from
``docutils.utils.punctuation_chars``.  Run this with the Python interpreter
(and docutils version) that docodin should mirror:

    python scripts/gen_unicode_tables.py > odin/rst/unicode_tables.odin
"""

from __future__ import annotations

import re
import sys
import unicodedata

from docutils.utils import punctuation_chars, urischemes


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, sys.maxunicode))
    return out


def expand_class(pattern: str) -> set[str]:
    """Expand a docutils regex character-class body into the set of chars."""
    rx = re.compile("[" + pattern + "]")
    return {chr(cp) for cp in range(sys.maxunicode + 1)
            if not 0xD800 <= cp <= 0xDFFF and rx.match(chr(cp))}


def emit_ranges(name: str, rs: list[tuple[int, int]]) -> None:
    print(f"@(rodata)\n{name} := [?][2]rune{{")
    line = "    "
    for lo, hi in rs:
        item = f"{{0x{lo:X}, 0x{hi:X}}}, "
        if len(line) + len(item) > 96:
            print(line.rstrip())
            line = "    "
        line += item
    if line.strip():
        print(line.rstrip())
    print("}\n")


def chars_to_ranges(chars: set[str]) -> list[tuple[int, int]]:
    cps = sorted(ord(c) for c in chars)
    out: list[tuple[int, int]] = []
    for cp in cps:
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def odin_rune(c: str) -> str:
    return f"0x{ord(c):X}"


def ascii_flags(start_prefix: str, end_suffix: str) -> list[int]:
    """ASCII fast-path bit flags: 1=space 2=alnum 4=start-prefix 8=end-suffix 16=punct7."""
    punct7 = re.compile(r'[!-/:-@[-`{-~]')
    return [bool(chr(cp).isspace()) | chr(cp).isalnum() << 1 | (chr(cp) in start_prefix) << 2
            | (chr(cp) in end_suffix) << 3 | bool(punct7.match(chr(cp))) << 4 for cp in range(128)]


def main() -> None:
    print("// Code generated by scripts/gen_unicode_tables.py; DO NOT EDIT.")
    print(f"// Unicode {unicodedata.unidata_version}, CPython {sys.version.split()[0]}.")
    print("package rst\n")

    emit_ranges("SPACE_RANGES", ranges(str.isspace))
    emit_ranges("ALNUM_RANGES", ranges(str.isalnum))
    emit_ranges("DECIMAL_RANGES", ranges(str.isdecimal))
    emit_ranges("COMBINING_RANGES", ranges(lambda c: unicodedata.combining(c) != 0))
    emit_ranges("WIDE_RANGES", ranges(lambda c: unicodedata.east_asian_width(c) in "WF"))

    openers = punctuation_chars.openers
    closers = punctuation_chars.closers
    assert len(openers) == len(closers)
    # Exactly the classes used by Inliner.init_customizations():
    #   start_string_prefix: (?<=\s|[openers delimiters])
    #   end_string_suffix:   (?=\s|[\x00 closing_delimiters delimiters closers])
    start_prefix = expand_class(openers + punctuation_chars.delimiters)
    end_suffix = expand_class('\x00' + punctuation_chars.closing_delimiters
                              + punctuation_chars.delimiters + closers)
    emit_ranges("START_PREFIX_RANGES", chars_to_ranges(start_prefix))
    emit_ranges("END_SUFFIX_RANGES", chars_to_ranges(end_suffix))

    flags = ascii_flags(start_prefix, end_suffix)
    print("@(rodata)\nASCII_FLAGS := [128]u8{")
    for i in range(0, 128, 16):
        print("    " + ", ".join(str(f) for f in flags[i:i + 16]) + ",")
    print("}\n")

    # match_chars(): openers.index(c1) is the *first* occurrence.
    pairs: dict[str, set[str]] = {}
    for i, o in enumerate(openers):
        if o not in pairs:
            pairs[o] = {closers[i]}
    for o, cs in punctuation_chars.quote_pairs.items():
        pairs.setdefault(o, set()).update(cs)
    print("@(rodata)\nQUOTE_PAIRS := [?][2]rune{")
    for o in sorted(pairs, key=ord):
        for c in sorted(pairs[o], key=ord):
            print(f"    {{{odin_rune(o)}, {odin_rune(c)}}},")
    print("}\n")

    print("@(rodata)\nURI_SCHEMES := [?]string{")
    for s in sorted(urischemes.schemes):
        print(f'    "{s}",')
    print("}")


if __name__ == "__main__":
    main()
