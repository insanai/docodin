"""Generate the rST language tables of the native reader from docutils' language modules.

The tables hold, per module of ``docutils.parsers.rst.languages``, the localized
directive and role names (``directives`` and ``roles``: local name -> canonical name).
Modules are sorted by name; each module's names are ranges of the flat name tables.
Two files are written (a file stays below 1408 lines):
``odin/reader/rst_language_tables.odin`` (the modules and directive names) and
``odin/reader/rst_role_tables.odin`` (the role names).  Run with the docutils version
the native pipeline mirrors:

    uv run --no-project --python 3.14 --with docutils==0.22.4 python \\
        scripts/gen_rst_language_tables.py
"""

from __future__ import annotations

import importlib
import pkgutil
from pathlib import Path

import docutils
import docutils.parsers.rst.languages as rst_languages
from gen_language_tables import odin_string

OUT = Path(__file__).resolve().parent.parent / "odin" / "reader"
HEADER = ("package reader\n\n"
          f"// Generated by scripts/gen_rst_language_tables.py from docutils {docutils.__version__};"
          " do not edit.\n")


def name_table(table: str, pairs: list[tuple[str, str]]) -> list[str]:
    lines = [f"@(rodata)\n{table} := [?][2]string {{"]
    lines += [f"\t{{{odin_string(local)}, {odin_string(canonical)}}}," for local, canonical in pairs]
    lines.append("}")
    return lines


def main() -> None:
    names = sorted(m.name for m in pkgutil.iter_modules(rst_languages.__path__))
    modules, directives, roles = [], [], []
    for name in names:
        mod = importlib.import_module("docutils.parsers.rst.languages." + name)
        modules.append((name, len(directives), len(mod.directives), len(roles), len(mod.roles)))
        directives += list(mod.directives.items())
        roles += list(mod.roles.items())
    lines = [HEADER,
             "// A module of ``docutils.parsers.rst.languages``: its ``directives`` and ``roles``",
             "// (local name -> canonical name) are ranges of ``RST_DIRECTIVE_NAMES`` and",
             "// ``RST_ROLE_NAMES`` (rst_role_tables.odin).",
             "Rst_Language :: struct {\n\tname:       string,\n\tdirectives: [2]int, // first, count",
             "\troles:      [2]int,\n}\n", "// The modules, sorted by name.",
             "@(rodata)\nRST_LANGUAGES := [?]Rst_Language {"]
    lines += [f"\t{{{odin_string(n)}, {{{d0}, {dn}}}, {{{r0}, {rn}}}}}," for n, d0, dn, r0, rn in modules]
    lines += ["}", ""] + name_table("RST_DIRECTIVE_NAMES", directives)
    (OUT / "rst_language_tables.odin").write_text("\n".join(lines) + "\n", encoding="utf-8")
    roles_lines = [HEADER] + name_table("RST_ROLE_NAMES", roles)
    (OUT / "rst_role_tables.odin").write_text("\n".join(roles_lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
