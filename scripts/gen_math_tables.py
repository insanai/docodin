# ------------

def l2m_handlers() -> list[str]:
    """Map every command named in a table to its handler (the first matching selector)."""
    tables = (latex2mathml.letters, latex2mathml.ordinary, latex2mathml.functions,
              latex2mathml.modulo_functions, latex2mathml.math_alphabets,
              latex2mathml.thick_operators, latex2mathml.small_operators,
              latex2mathml.operators, latex2mathml.bigdelimiters, latex2mathml.spaces,
              latex2mathml.fractions, latex2mathml.accents, latex2mathml.over,
              latex2mathml.under, latex2mathml.layout_styles)
    names = set().union(*tables) | {
        "boldsymbol", "pmb", "colon", "idotsint", "not", "text", "mbox", "textrm", "hspace",
        "mspace", "phantom", "boxed", "sqrt", "\\", "overset", "underset", "xleftarrow",
        "xrightarrow", "begin", "end"}
    rows = []
    for name in sorted(names, key=str.encode):
        handler = next(h for select, h in latex2mathml._CMD_HANDLERS if select(name))
        label = handler.__name__.removeprefix("_cmd_").removeprefix("handle_")
        rows.append(f"\t{{{odin_string(name)}, .{label.title()}}},")
    return table("L2M_COMMANDS", "L2m_Command", rows,
                 "The handler of each command known to ``_CMD_HANDLERS`` (except the "
                 "``*limits`` commands)")


def attrs_literal(attributes: dict[str, object]) -> str:
    items = (f"{{{odin_string(key)}, {odin_string(latex2mathml.MathElement.a_str(value))}}}"
             for key, value in attributes.items())
    return "{" + ", ".join(items) + "}"


def l2m_lines() -> list[str]:
    lm = latex2mathml
    modulo = [f"\t{{{odin_string(name)}, {str(b).lower()}, {str(n).lower()}, "
              f"{str(p).lower()}, {odin_string(pad)}}},"
              for name, (b, n, p, pad) in sorted(lm.modulo_functions.items(), key=utf8_key)]
    matrices = [f"\t{{{odin_string(name)}, {odin_string(left)}, {odin_string(right)}}},"
                for name, (left, right) in sorted(lm.matrices.items(), key=utf8_key)]
    styles = [f"\t{{{odin_string(name)}, {attrs_literal(attrs)}}},"
              for name, attrs in sorted(lm.layout_styles.items(), key=utf8_key)]
    fractions = [f"\t{{{odin_string(name)}, {attrs_literal(attrs)}}},"
                 for name, attrs in sorted(lm.fractions.items(), key=utf8_key)]
    return [
        *str_table("LETTERS", lm.letters, "``letters``"),
        *str_table("ORDINARY", lm.ordinary, "``ordinary``"),
        *str_table("FUNCTIONS", lm.functions, "``functions`` (``operatorname``: None)"),
        *str_table("OPERATORS", lm.operators, "``operators``"),
        *str_table("STRETCHABLES", lm.stretchables, "``stretchables``"),
        *str_table("THICK_OPERATORS", lm.thick_operators, "``thick_operators``"),
        *str_table("SMALL_OPERATORS", lm.small_operators, "``small_operators``"),
        *str_table("SPACES", lm.spaces, "``spaces``"),
        *str_table("ACCENTS", lm.accents, "``accents``"),
        *str_table("OVER", {k: v[0] for k, v in lm.over.items()}, "``over`` (characters)"),
        *str_table("UNDER", {k: v[0] for k, v in lm.under.items()}, "``under`` (characters)"),
        *str_table("ANOMALOUS_CHARS", lm.anomalous_chars, "``anomalous_chars``"),
        *str_table("BIG_DELIMITERS", {k: lm.delimiter_sizes[s] for k, s in lm.bigdelimiters.items()},
                   "``bigdelimiters`` with their ``delimiter_sizes``"),
        *name_list("L2M_GREEK_CAPITALS", lm.greek_capitals, "``greek_capitals``"),
        *name_list("MOVABLE_LIMITS", lm.movablelimits, "``movablelimits``"),
        *table("MODULO_FUNCTIONS", "Modulo_Entry", modulo, "``modulo_functions``"),
        *table("MATRICES", "Matrix_Entry", matrices, "``matrices``: fences"),
        *table("LAYOUT_STYLES", "Attrs_Entry", styles, "``layout_styles``"),
        *table("FRACTIONS", "Attrs_Entry", fractions, "``fractions``: attributes"),
    ]


def main() -> None:
    write("unicode_tables.odin", "Python unicodedata", unicode_lines())
    write("nfc_tables.odin", "Python unicodedata", nfc_lines())
    write("tex2unichar_tables.odin", "docutils/utils/math/tex2unichar.py", tex2unichar_lines())
    write("unichar2tex_tables.odin", "docutils/utils/math/unichar2tex.py", unichar2tex_lines())
    write("mathalphabet_tables.odin", "docutils/utils/math/mathalphabet2unichar.py",
          mathalphabet_lines())
    config = "docutils/utils/math/_math2html_config.py"
    write("math2html_command_tables.odin", config, m2h_command_lines())
    write("math2html_tables.odin", config, m2h_lines())
    source = "docutils/utils/math/latex2mathml.py"
    write("latex2mathml_command_tables.odin", source, l2m_handlers())
    write("latex2mathml_tables.odin", source, l2m_lines())


if __name__ == "__main__":
    main()
