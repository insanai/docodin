"""Generate the tables of the native math converters (``odin/math``, package ``texmath``).

The data comes from the shim's modules in ``python/docodin/shim/docutils/utils/math``:
the ``tex2unichar``, ``unichar2tex`` and ``mathalphabet2unichar`` dictionaries, the
configuration of ``math2html`` (``FormulaConfig``) and the character tables of
``latex2mathml``. The Unicode tables (Python's ``str.isalpha``, ``isdigit``, ``isspace``,
``isprintable``, ``upper`` and NFC normalization) come from the running Python's
``unicodedata``; generate them with the CPython version all native Unicode tables
use (3.14, see scripts/gen_doctree_tables.py):

    uv run --no-project --python 3.14 python scripts/gen_math_tables.py

Keys are sorted by their UTF-8 bytes (which is code point order) for binary searches.
"""

from __future__ import annotations

import sys
import unicodedata
from collections.abc import Callable, Iterable
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "odin" / "math"
sys.path.insert(0, str(ROOT / "python" / "docodin" / "shim"))

from docutils.utils.math import _math2html_hybrid as hybrid  # noqa: E402
from docutils.utils.math import (  # noqa: E402
    latex2mathml,
    mathalphabet2unichar,
    tex2unichar,
    unichar2tex,
)
from docutils.utils.math.math2html import (  # noqa: E402
    AlphaCommand,
    ContainerConfig,
    FormulaConfig,
    FormulaFactory,
)

MAX_RUNE = sys.maxunicode + 1
HEADER = "// Code generated by scripts/gen_math_tables.py; DO NOT EDIT.\n"


def odin_string(text: str | None) -> str:
    """An Odin string literal; non-printable, combining and non-ASCII space escaped."""
    out = []
    for char in text or "":
        if char in '"\\':
            out.append("\\" + char)
        elif (not char.isprintable() or (char.isspace() and char != " ")
              or unicodedata.combining(char) or unicodedata.category(char).startswith("M")):
            out.append(f"\\u{ord(char):04x}" if ord(char) < 0x10000 else f"\\U{ord(char):08x}")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def utf8_key(item: tuple[str, object]) -> bytes:
    return item[0].encode()


def packed(items: Iterable[str], indent: int = 1) -> list[str]:
    """Lay out literal `items` (each followed by a comma) in lines of at most 99 columns."""
    lines: list[str] = []
    line = ""
    for item in items:
        if line and 4 * indent + len(line) + len(item) + 2 > 99:
            lines.append("\t" * indent + line)
            line = ""
        line += (" " if line else "") + item + ","
    return [*lines, "\t" * indent + line] if line else lines


def table(name: str, kind: str, rows: list[str], doc: str) -> list[str]:
    return [f"// {doc}", "@(rodata)", f"{name} := [?]{kind}{{", *rows, "}", ""]


def str_table(name: str, mapping: dict[str, str | None], doc: str) -> list[str]:
    rows = [f"\t{{{odin_string(key)}, {odin_string(value)}}},"
            for key, value in sorted(mapping.items(), key=utf8_key)]
    return table(name, "Str_Entry", rows, doc)


def name_list(name: str, names: Iterable[str], doc: str) -> list[str]:
    items = sorted(set(names), key=str.encode)
    return table(name, "string", packed(odin_string(n) for n in items), doc)


def write(filename: str, source: str, lines: list[str]) -> None:
    text = HEADER + f"// Source: {source}\npackage texmath\n\n" + "\n".join(lines).rstrip() + "\n"
    (OUT / filename).write_text(text, encoding="utf-8")
    print(f"wrote odin/math/{filename} ({text.count(chr(10))} lines)")


# Unicode tables
# --------------

def ranges(test: Callable[[str], bool]) -> list[tuple[int, int]]:
    """The code point ranges (inclusive) of the characters passing `test`."""
    result: list[tuple[int, int]] = []
    for code in range(MAX_RUNE):
        if test(chr(code)):
            if result and result[-1][1] == code - 1:
                result[-1] = (result[-1][0], code)
            else:
                result.append((code, code))
    return result


def range_table(name: str, test: Callable[[str], bool], doc: str) -> list[str]:
    items = (f"{{0x{lo:x}, 0x{hi:x}}}" for lo, hi in ranges(test))
    return table(name, "[2]rune", packed(items), doc)


def decimal_zeros() -> list[int]:
    """The zero digits of the runs of ten decimal digits (for ``float()``)."""
    zeros = [code for code in range(MAX_RUNE) if unicodedata.decimal(chr(code), -1) == 0]
    for zero in zeros:
        assert all(unicodedata.decimal(chr(zero + d), -1) == d for d in range(10)), zero
    return zeros


def upper_lines() -> list[str]:
    items = []
    for code in range(MAX_RUNE):
        char = chr(code)
        if char.upper() != char:
            items.append(f"{{0x{code:x}, {odin_string(char.upper())}}}")
    return table("UPPER_CASE", "Rune_Entry", packed(items),
                 "``str.upper``: the characters with an upper case form")


def unicode_lines() -> list[str]:
    zeros = packed(f"0x{zero:x}" for zero in decimal_zeros())
    return [
        f'UNICODE_VERSION :: "{unicodedata.unidata_version}"', "",
        *range_table("ALPHA_RANGES", str.isalpha, "``str.isalpha``"),
        *range_table("DIGIT_RANGES", str.isdigit, "``str.isdigit``"),
        *range_table("SPACE_RANGES", str.isspace, "``str.isspace``"),
        *range_table("UNPRINTABLE_RANGES", lambda c: not c.isprintable(),
                     "not ``str.isprintable`` (escaped by ``repr``)"),
        *table("DECIMAL_ZEROS", "rune", zeros, "the zeros of the Unicode decimal digits"),
        *upper_lines(),
    ]


def canonical_decomposition(char: str) -> list[int] | None:
    decomposition = unicodedata.decomposition(char)
    if not decomposition or decomposition.startswith("<"):
        return None
    return [int(part, 16) for part in decomposition.split()]


def nfc_lines() -> list[str]:
    decompositions: list[str] = []
    compositions: list[tuple[int, int, int]] = []
    for code in range(MAX_RUNE):
        char = chr(code)
        if 0xAC00 <= code <= 0xD7A3:
            continue  # Hangul syllables are decomposed algorithmically
        parts = canonical_decomposition(char)
        if parts is None:
            continue
        text = "".join(chr(part) for part in parts)
        decompositions.append(f"{{0x{code:x}, {odin_string(text)}}}")
        if len(parts) == 2 and unicodedata.normalize("NFC", text) == char:
            compositions.append((parts[0], parts[1], code))
    classes: list[tuple[int, int, int]] = []
    for code in range(MAX_RUNE):
        ccc = unicodedata.combining(chr(code))
        if not ccc:
            continue
        if classes and classes[-1][1] == code - 1 and classes[-1][2] == ccc:
            classes[-1] = (classes[-1][0], code, ccc)
        else:
            classes.append((code, code, ccc))
    return [
        *table("DECOMPOSITIONS", "Rune_Entry", packed(decompositions),
               "canonical decompositions (one level; Hangul syllables excluded)"),
        *table("COMPOSITIONS", "Composition",
               packed(f"{{0x{a:x}, 0x{b:x}, 0x{c:x}}}" for a, b, c in sorted(compositions)),
               "primary composites: the pairs that NFC composes, sorted by (first, second)"),
        *table("COMBINING_CLASSES", "Combining_Class",
               packed((f"{{0x{lo:x}, 0x{hi:x}, {ccc}}}" for lo, hi, ccc in classes)),
               "canonical combining classes (ranges with a nonzero class)"),
    ]


# tex2unichar, unichar2tex, mathalphabet2unichar
# -----------------------------------------------

TEX2UNICHAR = ("mathaccent", "mathalpha", "mathbin", "mathclose", "mathfence", "mathop",
               "mathopen", "mathord", "mathover", "mathpunct", "mathradical", "mathrel",
               "mathunder", "space")
ALPHABETS = ("mathbb", "mathbf", "mathbfit", "mathcal", "mathfrak", "mathit", "mathsf",
             "mathsfbf", "mathsfbfit", "mathsfit", "mathtt")


def tex2unichar_lines() -> list[str]:
    lines = []
    for name in TEX2UNICHAR:
        lines += str_table("TEX2UNICHAR_" + name.upper(), getattr(tex2unichar, name),
                           f"``tex2unichar.{name}``")
    return lines


def unichar2tex_lines() -> list[str]:
    rows = [f"\t{{0x{code:x}, {odin_string(tex)}}},"
            for code, tex in sorted(unichar2tex.uni2tex_table.items())]
    return table("UNI2TEX_TABLE", "Rune_Entry", rows,
                 "``unichar2tex.uni2tex_table``: LaTeX for Unicode characters")


def mathalphabet_lines() -> list[str]:
    lines = []
    for name in ALPHABETS:
        lines += str_table("ALPHABET_" + name.upper(), getattr(mathalphabet2unichar, name),
                           f"``mathalphabet2unichar.{name}``")
    lines += table("ALPHABET_NAMES", "string", packed(odin_string(n) for n in ALPHABETS),
                   "The alphabets by name (sorted).")
    lines += ["// The tables of `ALPHABET_NAMES`.",
              "ALPHABET_TABLES := [?][]Str_Entry{",
              *packed(f"ALPHABET_{name.upper()}[:]" for name in ALPHABETS), "}", ""]
    return lines


# math2html
# ---------

def command_kind(kind: type) -> str:
    return "." + {"OneParamFunction": "One_Param", "HybridFunction": "Hybrid"}.get(
        kind.__name__, kind.__name__.replace("Command", "").replace("Function", ""))


def m2h_command_lines() -> list[str]:
    rows = []
    for order, kind in enumerate(FormulaFactory.commandtypes):
        for name, value in kind.commandmap.items():
            value = "" if isinstance(value, list) else value
            rows.append((name.encode(), order, name, command_kind(kind), value))
    rows.sort()
    items = [f"\t{{{odin_string(name)}, {kind}, {odin_string(value)}}},"
             for _, _, name, kind, value in rows]
    return table("M2H_COMMANDS", "Command_Entry", items,
                 "The command tables of ``FormulaFactory.commandtypes``, sorted by name "
                 "and then by precedence")


def write_nodes(nodes: tuple) -> list[str]:
    """Flatten a compiled write template: a function is followed by its contents."""
    out: list[str] = []
    for node in nodes:
        match node:
            case hybrid._Param(name, typename):
                typed = "true" if typename is not None else "false"
                out.append(f"{{.Param, {odin_string(name)}, {odin_string(typename)}, {typed}, 0, 0}}")
            case hybrid._Function(index, None):
                out.append(f'{{.Self_Closing, "", "", false, {index}, 0}}')
            case hybrid._Function(index, contents):
                inner = write_nodes(contents)
                out.append(f'{{.Function, "", "", false, {index}, {len(inner)}}}')
                out += inner
            case hybrid._Bracket(char):
                out.append(f'{{.Bracket, {odin_string(char)}, "", false, 0, 0}}')
            case hybrid._Text(char):
                out.append(f'{{.Text, {odin_string(char)}, "", false, 0, 0}}')
    return out


def hybrid_lines() -> list[str]:
    lines = ["// ``FormulaConfig.hybridfunctions`` with compiled templates and "
             "``hybridsizes``.", "@(rodata)", "HYBRID_FUNCTIONS := [?]Hybrid_Entry{"]
    for name, (read, write_template, *tags) in sorted(FormulaConfig.hybridfunctions.items(),
                                                      key=utf8_key):
        params = ", ".join(
            f"{{{odin_string(p.name)}, {str(p.literal).lower()}, {str(p.optional).lower()}}}"
            for p in hybrid.ParameterDefinition.fromtemplate(read))
        size = FormulaConfig.hybridsizes.get(name, "")
        lines.append(f"\t{{\n\t\tname = {odin_string(name)}, size = {odin_string(size)},")
        lines.append(f"\t\tparams = {{{params}}},")
        lines.append("\t\twrite = {")
        lines += [f"\t\t\t{node}," for node in write_nodes(hybrid._compile(write_template))]
        lines.append("\t\t},")
        lines += ["\t\ttags = {", *packed((odin_string(tag) for tag in tags), 3), "\t\t},"]
        lines.append("\t},")
    return [*lines, "}", ""]


def m2h_lines() -> list[str]:
    config = FormulaConfig
    brackets = [f"\t{{{odin_string(key)}, {{{', '.join(odin_string(p) for p in pieces)}}}}},"
                for key, pieces in sorted(config.bigbrackets.items(), key=utf8_key)]
    environments = [f"\t{{{odin_string(key)}, {{{', '.join(odin_string(a) for a in align)}}}}},"
                    for key, align in sorted(config.environments.items(), key=utf8_key)]
    unmodified = "".join(config.unmodified["characters"])
    return [
        *hybrid_lines(),
        *table("BIG_BRACKETS", "Pieces_Entry", brackets, "``FormulaConfig.bigbrackets``"),
        *table("ENVIRONMENTS", "Pieces_Entry", environments, "``FormulaConfig.environments``"),
        *str_table("MODIFIED", config.modified, "``FormulaConfig.modified``"),
        "// ``FormulaConfig.unmodified['characters']``",
        f"UNMODIFIED :: {odin_string(unmodified)}", "",
        *name_list("GREEK_CAPITALS", AlphaCommand.greek_capitals,
                   "``AlphaCommand.greek_capitals`` (upright)"),
        *name_list("EXTRACTED_CLASSES", ContainerConfig.extracttext["extracted"],
                   "``ContainerConfig.extracttext['extracted']``"),
    ]


