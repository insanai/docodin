"""Generate ``odin/writers/visitor_names_generated.odin`` from docutils' translators.

With the ``debug`` setting, ``NodeVisitor.dispatch_visit`` and ``dispatch_departure``
report the name of the method they call (``method.__name__``: an alias reports the
function it names).  The tables hold, per translator and node class, the names of the
visit and depart methods.  Run with the docutils version the native pipeline mirrors:

    uv run --no-project --python 3.14 --with docutils==0.22.4 python \\
        scripts/gen_visitor_names.py > odin/writers/visitor_names_generated.odin
"""

from __future__ import annotations

import docutils
from docutils import nodes
from docutils.writers import docutils_xml, html5_polyglot, latex2e, xetex

TRANSLATORS = (
    ("HTML5_METHOD_NAMES", html5_polyglot.HTMLTranslator),
    ("LATEX_METHOD_NAMES", latex2e.LaTeXTranslator),  # also XeLaTeXTranslator (checked)
    ("XML_METHOD_NAMES", docutils_xml.XMLTranslator),
)


def method_name(cls, prefix: str, name: str) -> str:
    fallback = "unknown_visit" if prefix == "visit_" else "unknown_departure"
    method = getattr(cls, prefix + name, None)
    return method.__name__ if method is not None else fallback


def main() -> None:
    print('package writers\n\nimport dt "../doctree"\n')
    print(f"// Generated by scripts/gen_visitor_names.py from docutils {docutils.__version__};"
          " do not edit.\n")
    print("// The visit and depart method names (``method.__name__``) of the translators by")
    print("// node class, for the debug messages of ``dispatch_visit`` and ``dispatch_departure``")
    print("// (``Element``: a plain element, of no node class).")
    names = [*nodes.node_class_names, "Element"]
    for name in names:  # the XeTeX translator inherits every method
        for prefix in ("visit_", "depart_"):
            assert (method_name(xetex.XeLaTeXTranslator, prefix, name)
                    == method_name(latex2e.LaTeXTranslator, prefix, name)), name
    for i, (table, cls) in enumerate(TRANSLATORS):
        if i > 0:
            print()
        print(f"@(rodata)\n{table} := [dt.Tag][2]string {{")
        for name in names:
            visit, depart = "unknown_visit", "unknown_departure"
            if name != "Element":
                visit = method_name(cls, "visit_", name)
                depart = method_name(cls, "depart_", name)
            print(f'\t.{name} = {{"{visit}", "{depart}"}},')
        print("}")


if __name__ == "__main__":
    main()
