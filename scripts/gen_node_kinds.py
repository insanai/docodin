"""Generate ``odin/rst/node_kinds.odin`` from ``docutils.nodes``.

The parser's node kinds (their numbers are part of the wire format read by
``python/docodin/builder.py``) with their docutils tag names.

    python scripts/gen_node_kinds.py > odin/rst/node_kinds.odin
"""

from __future__ import annotations

import docutils
import docutils.nodes as N

# (Odin name, docutils tag) of the parser kinds, in wire-format order.
PARSER_KINDS = [
    ("Document", "document"), ("Section", "section"), ("Section_Title", "section_title"),
    ("Title", "title"), ("Paragraph", "paragraph"), ("Bullet_List", "bullet_list"),
    ("Enumerated_List", "enumerated_list"), ("List_Item", "list_item"),
    ("Definition_List", "definition_list"), ("Definition_List_Item", "definition_list_item"),
    ("Term", "term"), ("Classifier", "classifier"), ("Definition", "definition"),
    ("Field_List", "field_list"), ("Field", "field"), ("Field_Name", "field_name"),
    ("Field_Body", "field_body"), ("Option_List", "option_list"),
    ("Option_List_Item", "option_list_item"), ("Option_Group", "option_group"),
    ("Option", "option"), ("Option_String", "option_string"),
    ("Option_Argument", "option_argument"), ("Description", "description"),
    ("Literal_Block", "literal_block"), ("Doctest_Block", "doctest_block"),
    ("Line_Block", "line_block"), ("Line", "line"), ("Block_Quote", "block_quote"),
    ("Attribution", "attribution"), ("Transition", "transition"), ("Table", "table"),
    ("TGroup", "tgroup"), ("Colspec", "colspec"), ("THead", "thead"), ("TBody", "tbody"),
    ("Row", "row"), ("Entry", "entry"), ("Footnote", "footnote"), ("Citation", "citation"),
    ("Label", "label"), ("Target", "target"),
    ("Substitution_Definition", "substitution_definition"), ("Comment", "comment"),
    ("Directive", "pending_directive"), ("Include_End", "include_end"),
    ("System_Message", "system_message"), ("Text", "#text"), ("Emphasis", "emphasis"),
    ("Strong", "strong"), ("Literal", "literal"), ("Inline_Target", "target"),
    ("Substitution_Reference", "substitution_reference"), ("Reference", "reference"),
    ("Footnote_Reference", "footnote_reference"), ("Citation_Reference", "citation_reference"),
    ("Interpreted", "pending_role"), ("Problematic", "problematic"),
]

def main() -> None:
    tags = {name: cls for name, cls in vars(N).items()
            if isinstance(cls, type) and issubclass(cls, N.Element)}
    for _, tag in PARSER_KINDS:
        assert tag in tags or tag.startswith(("pending_", "#", "section_title", "include_end")), tag
    print("// Code generated by scripts/gen_node_kinds.py; DO NOT EDIT.")
    print(f"// docutils {docutils.__version__}")
    print("package rst\n")
    print("// Node kinds of the parse tree.  The numbering is the wire format read by")
    print("// python/docodin/builder.py.")
    print("Node_Kind :: enum u8 {")
    for name, _ in PARSER_KINDS:
        print(f"\t{name},")
    print("}\n")
    print("// docutils tag names (``Element.tagname``; pseudo tags for parse events).")
    print("@(rodata)\nNODE_TAGS := [Node_Kind]string {")
    for name, tag in PARSER_KINDS:
        print(f'\t.{name} = "{tag}",')
    print("}")


if __name__ == "__main__":
    main()
