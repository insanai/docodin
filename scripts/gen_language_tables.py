"""Generate ``odin/transforms/language_tables.odin`` from docutils' language modules.

The table holds, per module of ``docutils.languages``, what the transforms read:
``labels``, ``bibliographic_fields`` and ``author_separators``.  Modules are sorted
by name for a binary search.  Run with the docutils version the native pipeline
mirrors:

    uv run --no-project --python 3.14 --with docutils==0.22.4 python \\
        scripts/gen_language_tables.py > odin/transforms/language_tables.odin
"""

from __future__ import annotations

import importlib
import pkgutil

import docutils
import docutils.languages

LABELS = ("author", "authors", "organization", "address", "contact", "version", "revision",
          "status", "date", "copyright", "dedication", "abstract", "attention", "caution",
          "danger", "error", "hint", "important", "note", "tip", "warning", "contents")


def odin_string(text: str) -> str:
    """An Odin string literal; non-printable characters and non-ASCII spaces escaped."""
    out = []
    for char in text:
        if char in '"\\':
            out.append("\\" + char)
        elif not char.isprintable() or (char.isspace() and char != " "):
            out.append(f"\\u{ord(char):04x}")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def module_entry(name: str) -> list[str]:
    mod = importlib.import_module("docutils.languages." + name)
    lines = [f"\t{{ // {name}", f"\t\tname = {odin_string(name)},", "\t\tlabels = {"]
    for label in LABELS:
        text = mod.labels.get(label)
        if text is not None:
            lines.append(f"\t\t\t.{label} = {odin_string(text)},")
    lines.append("\t\t},")
    missing = [label for label in LABELS if label not in mod.labels]
    if missing:
        lines.append("\t\tmissing = {" + ", ".join("." + m for m in missing) + "},")
    lines.append("\t\tfields = {")
    for key, canonical in mod.bibliographic_fields.items():
        lines.append(f"\t\t\t{{{odin_string(key)}, .{canonical}}},")
    lines.append("\t\t},")
    seps = ", ".join(odin_string(s) for s in mod.author_separators)
    lines.append(f"\t\tseparators = {{{seps}}},")
    lines.append("\t},")
    return lines


def main() -> None:
    names = sorted(m.name for m in pkgutil.iter_modules(docutils.languages.__path__))
    print("// Code generated by scripts/gen_language_tables.py; DO NOT EDIT.")
    print(f"// docutils {docutils.__version__} (docutils.languages).")
    print("package transforms\n")
    print("// A label of ``language.labels``.")
    print("Label :: enum u8 {")
    for label in LABELS:
        print(f"\t{label},")
    print("}\n")
    print("// The language modules, sorted by module name.")
    print("@(rodata)")
    print("LANGUAGE_MODULES := [?]Language_Module{")
    for name in names:
        print("\n".join(module_entry(name)))
    print("}")


if __name__ == "__main__":
    main()
