"""Generate ``odin/writers/tables_generated.odin`` from the shim's data modules.

The tables are the language-dependent ``labels`` and ``author_separators`` of
``docutils.languages``, read from the generated shim modules in
``python/docodin/shim/docutils/languages``:

    uv run python scripts/gen_writer_tables.py > odin/writers/tables_generated.odin
"""

from __future__ import annotations

import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHIM = ROOT / "python" / "docodin" / "shim" / "docutils"
LABELS = ("author", "authors", "organization", "address", "contact", "version", "revision",
          "status", "date", "copyright", "dedication", "abstract", "attention", "caution",
          "danger", "error", "hint", "important", "note", "tip", "warning", "contents")


def odin_string(text: str) -> str:
    """An Odin string literal; non-printable and non-ASCII spaces escaped."""
    out = []
    for char in text:
        if char in '"\\':
            out.append("\\" + char)
        elif not char.isprintable() or (char.isspace() and char != " "):
            out.append(f"\\u{ord(char):04x}")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def languages() -> None:
    print("// The labels of ``docutils.languages.<code>.labels``.")
    print("Label :: enum u8 {")
    for label in LABELS:
        print(f"\t{label},")
    print("}\n")
    print("// The language modules of ``docutils.languages``, sorted by module name.")
    print("@(rodata)\nLANGUAGE_MODULES := [?]Language_Module{")
    for path in sorted((SHIM / "languages").glob("[a-z]*.py")):
        data = runpy.run_path(str(path))
        labels = data["labels"]
        assert sorted(labels) == sorted(LABELS), path.name
        print(f"\t{{\n\t\tname = {odin_string(path.stem)},\n\t\tlabels = {{")
        for label in LABELS:
            print(f"\t\t\t.{label} = {odin_string(labels[label])},")
        seps = ", ".join(odin_string(s) for s in data["author_separators"])
        print(f"\t\t}},\n\t\tauthor_separators = {{{seps}}},\n\t}},")
    print("}")


def main() -> None:
    print("// Code generated by scripts/gen_writer_tables.py; DO NOT EDIT.")
    print("// Source: python/docodin/shim/docutils/languages/*.py")
    print("package writers\n")
    languages()


if __name__ == "__main__":
    main()
