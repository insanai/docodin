"""Generate ``odin/text/smartquotes_tables.odin`` from the shim's quote data.

The table is ``docutils.utils.smartquotes.smartchars.quotes`` as generated
into ``python/docodin/shim/docutils/utils/_smartquotes_data.py``, sorted by
language tag for a binary search:

    uv run python scripts/gen_smartquotes_tables.py > odin/text/smartquotes_tables.odin
"""

from __future__ import annotations

import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "python" / "docodin" / "shim" / "docutils" / "utils" / "_smartquotes_data.py"


def odin_string(text: str) -> str:
    """An Odin string literal; non-printable and non-ASCII spaces escaped."""
    out = []
    for char in text:
        if char in '"\\':
            out.append("\\" + char)
        elif not char.isprintable() or (char.isspace() and char != " "):
            out.append(f"\\u{ord(char):04x}")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def main() -> None:
    quotes = runpy.run_path(str(DATA))["quotes"]
    print("// Code generated by scripts/gen_smartquotes_tables.py; DO NOT EDIT.")
    print("// Source: python/docodin/shim/docutils/utils/_smartquotes_data.py")
    print("package text\n")
    print("// ``smartchars.quotes``: open/close primary, open/close secondary quotes.")
    print("@(rodata)\nLANGUAGE_QUOTES := [?]Language_Quotes{")
    for tag in sorted(quotes):
        marks = quotes[tag]
        assert len(marks) == 4, tag
        fields = ", ".join(odin_string(mark) for mark in marks)
        print(f"\t{{{odin_string(tag)}, {{{fields}}}}},")
    print("}")


if __name__ == "__main__":
    main()
