"""Generate the data modules of docodin's docutils implementation.

Language tables (labels, bibliographic field names, directive and role
names), URI schemes and punctuation character classes are data; they are
extracted from an installed docutils (a development-time dependency only):

    python scripts/gen_shim_data.py

Writes into ``python/docodin/shim/docutils``.
"""

from __future__ import annotations

import importlib
import pkgutil
import shutil
import unicodedata
from pathlib import Path

import docutils
import docutils.languages
import docutils.parsers.rst.languages
from docutils.utils import punctuation_chars, smartquotes, urischemes
from docutils.utils.math import mathalphabet2unichar, tex2unichar, unichar2tex

ROOT = Path(__file__).resolve().parent.parent / "python" / "docodin" / "shim" / "docutils"
HEADER = "# Code generated by scripts/gen_shim_data.py from docutils {version}; DO NOT EDIT.\n"
LINE_LIMIT = 99


def _literal(value: object, indent: int) -> str:
    """Python source of `value`, one item per line for containers."""
    pad = " " * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = [f"{pad}    {k!r}: {_literal(v, indent + 4)}," for k, v in value.items()]
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    if isinstance(value, str) and len(repr(value)) + indent > LINE_LIMIT - 20:
        words = value.split(" ")
        chunks, current = [], ""
        for word in words:
            if current and len(repr(current + " " + word)) > 60:
                chunks.append(current + " ")
                current = word
            else:
                current = f"{current} {word}" if current else word
        chunks.append(current)
        return "(" + f"\n{pad}     ".join(repr(chunk) for chunk in chunks) + ")"
    if isinstance(value, list):
        flat = repr(value)
        if len(flat) + indent < LINE_LIMIT - 10:
            return flat
        return "[\n" + "\n".join(f"{pad}    {item!r}," for item in value) + f"\n{pad}]"
    return repr(value)


def _module(docstring: str, names: dict[str, object]) -> str:
    body = [HEADER.format(version=docutils.__version__), f'"""{docstring}"""\n']
    body.append('__docformat__ = "reStructuredText"\n')
    for name, value in names.items():
        body.append(f"{name} = {_literal(value, 0)}\n")
    return "\n".join(body)


def _language_codes(package: object) -> list[str]:
    return sorted(info.name for info in pkgutil.iter_modules(package.__path__))


def generate_languages() -> None:
    """``docutils.languages.<code>`` and ``docutils.parsers.rst.languages.<code>``."""
    for code in _language_codes(docutils.languages):
        module = importlib.import_module(f"docutils.languages.{code}")
        text = _module(f"Language-dependent labels and field names ({code}).", {
            "labels": module.labels,
            "bibliographic_fields": module.bibliographic_fields,
            "author_separators": module.author_separators,
        })
        (ROOT / "languages" / f"{code}.py").write_text(text, encoding="utf-8")
    for code in _language_codes(docutils.parsers.rst.languages):
        module = importlib.import_module(f"docutils.parsers.rst.languages.{code}")
        text = _module(f"reStructuredText directive and role names ({code}).", {
            "directives": module.directives,
            "roles": module.roles,
        })
        (ROOT / "parsers" / "rst" / "languages" / f"{code}.py").write_text(text,
                                                                         encoding="utf-8")


def _chunks(text: str, width: int = 60) -> str:
    """A long string as implicitly concatenated literals."""
    parts = [repr(text[i:i + width]) for i in range(0, len(text), width)]
    return "(\n    " + "\n    ".join(parts) + "\n)" if len(parts) > 1 else parts[0]


def generate_punctuation() -> None:
    """Character classes of the inline markup recognition rules."""
    names = ("openers", "closers", "delimiters", "closing_delimiters")
    lines = [HEADER.format(version=docutils.__version__),
             '"""Unicode punctuation character classes for inline markup recognition."""\n',
             '__docformat__ = "reStructuredText"\n']
    for name in names:
        lines.append(f"{name} = {_chunks(getattr(punctuation_chars, name))}\n")
    lines.append(f"quote_pairs = {_literal(punctuation_chars.quote_pairs, 0)}\n")
    (ROOT / "utils" / "_punctuation_data.py").write_text("\n".join(lines), encoding="utf-8")


def generate_smartquotes() -> None:
    text = _module("Quotation marks per language (primary open/close, secondary open/close).",
                   {"quotes": smartquotes.smartchars.quotes})
    (ROOT / "utils" / "_smartquotes_data.py").write_text(text, encoding="utf-8")


def generate_urischemes() -> None:
    text = _module("Known URI schemes (for standalone hyperlink recognition).",
                   {"schemes": urischemes.schemes})
    (ROOT / "utils" / "urischemes.py").write_text(text, encoding="utf-8")


def _char_comment(chars: str, prefix: str) -> str:
    """`prefix` with a trailing comment naming `chars`, cut to the line limit."""
    names = " ".join(unicodedata.name(ch, f"U+{ord(ch):04X}") for ch in chars)
    shown = chars if chars.isprintable() else ""
    line = f"{prefix}  # {shown} {names}"
    return line if len(line) <= LINE_LIMIT else line[:LINE_LIMIT - 1] + "…"


def _char_tables(module: object, docstring: str) -> str:
    """Source of a module of ``{name: dict}`` character tables, one entry per line."""
    lines = [HEADER.format(version=docutils.__version__), f'"""{docstring}"""\n',
             '__docformat__ = "reStructuredText"\n']
    for name, table in vars(module).items():
        if name.startswith("_") or not isinstance(table, dict):
            continue
        entries = [_char_comment(value, f"    {ascii(key)}: {ascii(value)},")
                   for key, value in table.items()]
        lines.append(f"{name} = {{\n" + "\n".join(entries) + "\n}\n")
    return "\n".join(lines)


def generate_math_tables() -> None:
    """LaTeX math <-> Unicode translation tables of ``docutils.utils.math``."""
    target = ROOT / "utils" / "math"
    text = _char_tables(tex2unichar, "LaTeX math to Unicode symbols translation dictionaries.")
    (target / "tex2unichar.py").write_text(text, encoding="utf-8")
    text = _char_tables(mathalphabet2unichar,
                        "LaTeX math to Unicode symbols translation dictionaries for the content\n"
                        "of math alphabet commands (mathtt, mathbf, ...).")
    (target / "mathalphabet2unichar.py").write_text(text, encoding="utf-8")
    entries = [f"    {code:#x}: {value!r}," for code, value in unichar2tex.uni2tex_table.items()]
    lines = [HEADER.format(version=docutils.__version__),
             '"""Unicode to LaTeX math translation table (for use with `str.translate`)."""\n',
             '__docformat__ = "reStructuredText"\n',
             "uni2tex_table = {\n" + "\n".join(entries) + "\n}\n"]
    (target / "unichar2tex.py").write_text("\n".join(lines), encoding="utf-8")


WRITER_DATA = {
    "writers/html4css1": ["html4css1.css", "template.txt"],
    "writers/html5_polyglot": ["minimal.css", "plain.css", "responsive.css", "italic-field-names.css",
                               "math.css", "tuftig.css", "template.txt"],
    "writers/latex2e": ["default.tex", "docutils.sty", "titlepage.tex", "titlingpage.tex",
                        "xelatex.tex"],
    "writers/pep_html": ["pep.css", "template.txt"],
    "writers/s5_html": ["themes"],
    "writers/odf_odt": ["styles.odt"],
    "parsers/rst": ["include"],
}


def copy_writer_data() -> None:
    """Writer stylesheets and templates, and the standard include files (kept identical)."""
    source_root = Path(docutils.__file__).parent
    for directory, names in WRITER_DATA.items():
        (ROOT / directory).mkdir(parents=True, exist_ok=True)
        for name in names:
            source = source_root / directory / name
            target = ROOT / directory / name
            if source.is_dir():
                shutil.copytree(source, target, dirs_exist_ok=True)
            elif source.exists():
                shutil.copyfile(source, target)


def main() -> None:
    for directory in ("languages", "parsers/rst/languages", "utils", "utils/math"):
        (ROOT / directory).mkdir(parents=True, exist_ok=True)
    generate_languages()
    generate_punctuation()
    generate_urischemes()
    generate_smartquotes()
    generate_math_tables()
    copy_writer_data()


if __name__ == "__main__":
    main()
