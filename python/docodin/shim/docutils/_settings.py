"""Option specifications of the "General Docutils Options" (`frontend.OptionParser`)."""

from __future__ import annotations

from collections.abc import Callable
from optparse import SUPPRESS_HELP
from typing import Any

THRESHOLD_CHOICES = ("info", "1", "warning", "2", "error", "3", "severe", "4", "none", "5")


def _output_options() -> list[tuple]:
    from docutils.frontend import validate_boolean

    return [
        ("Output destination name. Obsoletes the <destination> positional argument. "
         "Default: None (stdout).", ["--output-path", "--output"], {"metavar": "<destination>"}),
        ("Specify the document title as metadata.", ["--title"], {"metavar": "<title>"}),
        ('Include a "Generated by Docutils" credit and link.', ["--generator", "-g"],
         {"action": "store_true", "validator": validate_boolean}),
        ("Do not include a generator credit.", ["--no-generator"],
         {"action": "store_false", "dest": "generator"}),
        ("Include the date at the end of the document (UTC).", ["--date", "-d"],
         {"action": "store_const", "const": "%Y-%m-%d", "dest": "datestamp"}),
        ("Include the time & date (UTC).", ["--time", "-t"],
         {"action": "store_const", "const": "%Y-%m-%d %H:%M UTC", "dest": "datestamp"}),
        ("Do not include a datestamp of any kind.", ["--no-datestamp"],
         {"action": "store_const", "const": None, "dest": "datestamp"}),
        ('Base directory for absolute paths when reading from the local filesystem. '
         'Default "".', ["--root-prefix"], {"default": "", "metavar": "<path>"}),
        ('Include a "View document source" link.', ["--source-link", "-s"],
         {"action": "store_true", "validator": validate_boolean}),
        ("Use <URL> for a source link; implies --source-link.", ["--source-url"],
         {"metavar": "<URL>"}),
    ]


def _structure_options(store_multiple: Callable[..., None]) -> list[tuple]:
    from docutils.frontend import validate_boolean, validate_strip_class

    return [
        ('Do not include a "View document source" link.', ["--no-source-link"],
         {"action": "callback", "callback": store_multiple,
          "callback_args": ("source_link", "source_url")}),
        ("Link from section headers to TOC entries.  (default)", ["--toc-entry-backlinks"],
         {"dest": "toc_backlinks", "action": "store_const", "const": "entry",
          "default": "entry"}),
        ("Link from section headers to the top of the TOC.", ["--toc-top-backlinks"],
         {"dest": "toc_backlinks", "action": "store_const", "const": "top"}),
        ("Disable backlinks to the table of contents.", ["--no-toc-backlinks"],
         {"dest": "toc_backlinks", "action": "store_false"}),
        ("Link from footnotes/citations to references. (default)", ["--footnote-backlinks"],
         {"action": "store_true", "default": True, "validator": validate_boolean}),
        ("Disable backlinks from footnotes and citations.", ["--no-footnote-backlinks"],
         {"dest": "footnote_backlinks", "action": "store_false"}),
        ("Enable section numbering by Docutils.  (default)", ["--section-numbering"],
         {"action": "store_true", "dest": "sectnum_xform", "default": True,
          "validator": validate_boolean}),
        ("Disable section numbering by Docutils.", ["--no-section-numbering"],
         {"action": "store_false", "dest": "sectnum_xform"}),
        ("Remove comment elements from the document tree.", ["--strip-comments"],
         {"action": "store_true", "validator": validate_boolean}),
        ("Leave comment elements in the document tree. (default)", ["--leave-comments"],
         {"action": "store_false", "dest": "strip_comments"}),
        ('Remove all elements with classes="<class>" from the document tree. Warning: '
         "potentially dangerous; use with caution. (Multiple-use option.)",
         ["--strip-elements-with-class"],
         {"action": "append", "dest": "strip_elements_with_classes", "metavar": "<class>",
          "validator": validate_strip_class}),
        ('Remove all classes="<class>" attributes from elements in the document tree. '
         "Warning: potentially dangerous; use with caution. (Multiple-use option.)",
         ["--strip-class"],
         {"action": "append", "dest": "strip_classes", "metavar": "<class>",
          "validator": validate_strip_class}),
    ]


def _report_options() -> list[tuple]:
    from docutils.frontend import validate_boolean, validate_threshold

    return [
        ('Report system messages at or higher than <level>: "info" or "1", "warning"/"2" '
         '(default), "error"/"3", "severe"/"4", "none"/"5"', ["--report", "-r"],
         {"choices": THRESHOLD_CHOICES, "default": 2, "dest": "report_level",
          "metavar": "<level>", "validator": validate_threshold}),
        ('Report all system messages.  (Same as "--report=1".)', ["--verbose", "-v"],
         {"action": "store_const", "const": 1, "dest": "report_level"}),
        ('Report no system messages.  (Same as "--report=5".)', ["--quiet", "-q"],
         {"action": "store_const", "const": 5, "dest": "report_level"}),
        ("Halt execution at system messages at or above <level>.  Levels as in --report.  "
         "Default: 4 (severe).", ["--halt"],
         {"choices": THRESHOLD_CHOICES, "dest": "halt_level", "default": 4,
          "metavar": "<level>", "validator": validate_threshold}),
        ('Halt at the slightest problem.  Same as "--halt=info".', ["--strict"],
         {"action": "store_const", "const": 1, "dest": "halt_level"}),
        ("Enable a non-zero exit status for non-halting system messages at or above "
         "<level>.  Default: 5 (disabled).", ["--exit-status"],
         {"choices": THRESHOLD_CHOICES, "dest": "exit_status_level", "default": 5,
          "metavar": "<level>", "validator": validate_threshold}),
        ("Enable debug-level system messages and diagnostics.", ["--debug"],
         {"action": "store_true", "validator": validate_boolean}),
        ("Disable debug output.  (default)", ["--no-debug"],
         {"action": "store_false", "dest": "debug"}),
        ("Send the output of system messages to <file>.", ["--warnings"],
         {"dest": "warning_stream", "metavar": "<file>"}),
        ("Enable Python tracebacks when Docutils is halted.", ["--traceback"],
         {"action": "store_true", "default": None, "validator": validate_boolean}),
        ("Disable Python tracebacks.  (default)", ["--no-traceback"],
         {"dest": "traceback", "action": "store_false"}),
    ]


def _encoding_options(default_error_encoding: str) -> list[tuple]:
    from docutils.frontend import (
        validate_encoding_and_error_handler,
        validate_encoding_error_handler,
    )

    return [
        ("Specify the encoding and optionally the error handler of input text.  "
         "Default: utf-8.", ["--input-encoding"],
         {"metavar": "<name[:handler]>", "default": "utf-8",
          "validator": validate_encoding_and_error_handler}),
        (SUPPRESS_HELP, ["--input-encoding-error-handler"],
         {"default": "strict", "validator": validate_encoding_error_handler}),
        ("Specify the text encoding and optionally the error handler for output.  "
         "Default: utf-8.", ["--output-encoding"],
         {"metavar": "<name[:handler]>", "default": "utf-8",
          "validator": validate_encoding_and_error_handler}),
        (SUPPRESS_HELP, ["--output-encoding-error-handler"],
         {"default": "strict", "validator": validate_encoding_error_handler}),
        ("Specify text encoding and optionally the error handler for error output.  "
         f"Default: {default_error_encoding}.", ["--error-encoding", "-e"],
         {"metavar": "<name[:handler]>", "default": default_error_encoding,
          "validator": validate_encoding_and_error_handler}),
        (SUPPRESS_HELP, ["--error-encoding-error-handler"],
         {"default": "backslashreplace", "validator": validate_encoding_error_handler}),
    ]


def _misc_options(read_config_file: Callable[..., None]) -> list[tuple]:
    from docutils.frontend import (
        validate_colon_separated_string_list,
        validate_dependency_file,
    )

    return [
        ("Specify the language (as BCP 47 language tag).  Default: en.", ["--language", "-l"],
         {"dest": "language_code", "default": "en", "metavar": "<tag>"}),
        ("Write output file dependencies to <file>.", ["--record-dependencies"],
         {"metavar": "<file>", "validator": validate_dependency_file, "default": None}),
        ("Read configuration settings from <file>, if it exists.", ["--config"],
         {"metavar": "<file>", "type": "string", "action": "callback",
          "callback": read_config_file}),
        ("Show this program's version number and exit.", ["--version", "-V"],
         {"action": "version"}),
        ("Show this help message and exit.", ["--help", "-h"], {"action": "help"}),
        (SUPPRESS_HELP, ["--id-prefix"], {"default": ""}),
        (SUPPRESS_HELP, ["--auto-id-prefix"], {"default": "%"}),
        (SUPPRESS_HELP, ["--dump-settings"], {"action": "store_true"}),
        (SUPPRESS_HELP, ["--dump-internals"], {"action": "store_true"}),
        (SUPPRESS_HELP, ["--dump-transforms"], {"action": "store_true"}),
        (SUPPRESS_HELP, ["--dump-pseudo-xml"], {"action": "store_true"}),
        (SUPPRESS_HELP, ["--expose-internal-attribute"],
         {"action": "append", "dest": "expose_internals",
          "validator": validate_colon_separated_string_list}),
        (SUPPRESS_HELP, ["--strict-visitor"], {"action": "store_true"}),
    ]


def general_options(default_error_encoding: str, store_multiple: Callable[..., None],
                    read_config_file: Callable[..., None]) -> tuple[Any, ...]:
    """All option tuples of the general settings group, in docutils' order."""
    return tuple(_output_options() + _structure_options(store_multiple) + _report_options()
                 + _encoding_options(default_error_encoding) + _misc_options(read_config_file))
