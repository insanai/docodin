"""Transforms needed by most or all documents."""

from __future__ import annotations

import re
import time
from collections.abc import Iterable, Iterator
from typing import Any

from docutils import nodes, utils
from docutils.transforms import Transform
from docutils.utils import smartquotes

__docformat__ = "reStructuredText"


class Decorations(Transform):
    """Populate a document's decoration element (header, footer)."""

    default_priority = 820

    def apply(self) -> None:
        header_nodes = self.generate_header()
        if header_nodes:
            self.document.get_decoration().get_header().extend(header_nodes)
        footer_nodes = self.generate_footer()
        if footer_nodes:
            self.document.get_decoration().get_footer().extend(footer_nodes)

    def generate_header(self) -> list[nodes.Node] | None:
        return None

    def generate_footer(self) -> list[nodes.Node] | None:
        """Source link, datestamp and generator credit, as configured."""
        settings = self.document.settings
        if not (settings.generator or settings.datestamp or settings.source_link
                or settings.source_url):
            return None
        text: list[nodes.Node] = []
        if settings.source_link and settings._source or settings.source_url:
            source = settings.source_url or utils.relative_path(settings.output_path,
                                                                settings._source)
            text.extend([nodes.reference("", "View document source", refuri=source),
                         nodes.Text(".\n")])
        if settings.datestamp:
            datestamp = time.strftime(settings.datestamp, time.gmtime())
            text.append(nodes.Text("Generated on: " + datestamp + ".\n"))
        if settings.generator:
            text.extend([
                nodes.Text("Generated by "),
                nodes.reference("", "Docutils", refuri="https://docutils.sourceforge.io/"),
                nodes.Text(" from "),
                nodes.reference("", "reStructuredText",
                                refuri="https://docutils.sourceforge.io/rst.html"),
                nodes.Text(" source.\n")])
        return [nodes.paragraph("", "", *text)]


class ExposeInternals(Transform):
    """Expose internal attributes if ``expose_internals`` is set."""

    default_priority = 840

    def not_Text(self, node: nodes.Node) -> bool:  # noqa: N802 - docutils name
        return not isinstance(node, nodes.Text)

    def apply(self) -> None:
        if self.document.settings.expose_internals:
            for node in self.document.findall(self.not_Text):
                for att in self.document.settings.expose_internals:
                    value = getattr(node, att, None)
                    if value is not None:
                        node["internal:" + att] = value


class Messages(Transform):
    """Place loose system messages in a "Docutils System Messages" section."""

    default_priority = 860

    def apply(self) -> None:
        messages = [*self.document.parse_messages, *self.document.transform_messages]
        loose_messages = [msg for msg in messages if not msg.parent]
        if loose_messages:
            section = nodes.section(classes=["system-messages"])
            section += nodes.title("", "Docutils System Messages")
            section += loose_messages
            self.document.transform_messages[:] = []
            self.document += section


class FilterMessages(Transform):
    """Remove system messages below the verbosity threshold."""

    default_priority = 870

    def apply(self) -> None:
        removed_ids = []
        for node in tuple(self.document.findall(nodes.system_message)):
            if node["level"] < self.document.reporter.report_level:
                node.parent.remove(node)
                for id in node["ids"]:
                    self.document.ids.pop(id, None)
                    removed_ids.append(id)
        for node in tuple(self.document.findall(nodes.problematic)):
            if "refid" in node and node["refid"] in removed_ids:
                node.parent.replace(node, nodes.Text(node.astext()))
        for node in self.document.findall(nodes.section):
            if "system-messages" in node["classes"] and len(node) == 1:
                node.parent.remove(node)


class TestMessages(Transform):
    """Append all post-parse system messages to the end (for testing)."""

    __test__ = False
    default_priority = 880

    def apply(self) -> None:
        for msg in self.document.transform_messages:
            if not msg.parent:
                self.document += msg


class StripComments(Transform):
    """Remove comment elements if ``strip_comments`` is set."""

    default_priority = 740

    def apply(self) -> None:
        if self.document.settings.strip_comments:
            for node in tuple(self.document.findall(nodes.comment)):
                node.parent.remove(node)


class StripClassesAndElements(Transform):
    """Remove elements with given classes, and given class values."""

    default_priority = 420

    def apply(self) -> None:
        settings = self.document.settings
        if settings.strip_elements_with_classes:
            self.strip_elements = {*settings.strip_elements_with_classes}
            for node in tuple(self.document.findall(self.check_classes)):
                node.parent.remove(node)
        if not settings.strip_classes:
            return
        for node in self.document.findall(nodes.Element):
            for class_value in settings.strip_classes:
                if class_value in node["classes"]:
                    node["classes"].remove(class_value)

    def check_classes(self, node: nodes.Node) -> bool:
        if not isinstance(node, nodes.Element):
            return False
        return any(class_value in self.strip_elements for class_value in node["classes"])


class SmartQuotes(Transform):
    """Replace ASCII quotation marks with typographic ones."""

    default_priority = 855
    nodes_to_skip = (nodes.FixedTextElement, nodes.Special)
    literal_nodes = (nodes.FixedTextElement, nodes.Special, nodes.image, nodes.literal,
                     nodes.math, nodes.raw, nodes.problematic)
    smartquotes_action = "qDe"

    def __init__(self, document: Any, startnode: Any) -> None:
        Transform.__init__(self, document, startnode=startnode)
        self.unsupported_languages: set[str] = set()

    def get_tokens(self, txtnodes: Iterable[nodes.Text]) -> Iterator[tuple[str, str]]:
        for node in txtnodes:
            if (isinstance(node.parent, self.literal_nodes)
                    or isinstance(node.parent.parent, self.literal_nodes)):
                yield "literal", str(node)
            else:
                # escaped quotes and dashes stay literal: restore the backslash
                yield "plain", re.sub(r"(?<=\x00)([-\\'\".`])", r"\\\1", str(node))

    def apply(self) -> None:
        smart_quotes = self.document.settings.setdefault("smart_quotes", False)
        if not smart_quotes:
            return
        alternative = isinstance(smart_quotes, str) and smart_quotes.startswith("alt")
        lc_smartquotes = self.document.settings.smartquotes_locales
        if lc_smartquotes:
            smartquotes.smartchars.quotes.update(dict(lc_smartquotes))
        for node in self.document.findall(nodes.TextElement):
            if isinstance(node, self.nodes_to_skip) or isinstance(node.parent, nodes.TextElement):
                continue
            self._educate(node, alternative)
        self.unsupported_languages.clear()

    def _educate(self, node: nodes.TextElement, alternative: bool) -> None:
        txtnodes = [txtnode for txtnode in node.findall(nodes.Text)
                    if not isinstance(txtnode.parent, nodes.option_string)]
        lang = self._language(node, alternative)
        teacher = smartquotes.educate_tokens(self.get_tokens(txtnodes),
                                             attr=self.smartquotes_action, language=lang)
        for txtnode, newtext in zip(txtnodes, teacher, strict=False):
            txtnode.parent.replace(txtnode, nodes.Text(newtext))

    def _language(self, node: nodes.TextElement, alternative: bool) -> str:
        lang = node.get_language_code(self.document.settings.language_code)
        if alternative:
            lang = lang.replace("-x-altquot", "") if "-x-altquot" in lang else lang + "-x-altquot"
        for tag in utils.normalize_language_tag(lang):
            if tag in smartquotes.smartchars.quotes:
                return tag
        if lang not in self.unsupported_languages:
            self.document.reporter.warning('No smart quotes defined for language "%s".' % lang,
                                           base_node=node)
        self.unsupported_languages.add(lang)
        return ""


class Validate(Transform):
    """Validate the document tree against the Docutils Document Model."""

    default_priority = 835

    def apply(self) -> None:
        if not getattr(self.document.settings, "validate", False):
            return
        for node in self.document.findall():
            try:
                node.validate(recursive=False)
            except nodes.ValidationError as e:
                self.document.reporter.warning(str(e),
                                               base_node=e.problematic_element or node)
